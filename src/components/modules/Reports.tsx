"use client";
import { useState } from "react";
import { motion } from "framer-motion";
import jsPDF from "jspdf";

interface Dam {
  id: number;
  name: string;
  state: string;
  waterLevel: number;
  maxWaterLevel: number;
  currentCapacity: number;
  maxCapacity: number;
  inflowRate: number;
  outflowRate: number;
  gatesOpen: number;
  totalGates: number;
  safetyStatus: string;
}

export default function Reports() {
  const [generating, setGenerating] = useState<string | null>(null);
  const [reportType, setReportType] = useState("daily");

  const generatePDF = async () => {
    setGenerating("pdf");
    const res = await fetch("/api/dams");
    const json = await res.json();
    const dams: Dam[] = json.dams || [];

    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();

    // Header
    doc.setFillColor(37, 99, 235);
    doc.rect(0, 0, pageWidth, 35, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(18);
    doc.setFont("helvetica", "bold");
    doc.text("DamGuard - Dam Monitoring Report", pageWidth / 2, 15, { align: "center" });
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text(`Generated: ${new Date().toLocaleString("en-IN")} | Type: ${reportType.toUpperCase()}`, pageWidth / 2, 25, { align: "center" });

    // Summary
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(13);
    doc.setFont("helvetica", "bold");
    doc.text("Executive Summary", 14, 50);

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    const totalGatesOpen = dams.reduce((s, d) => s + (d.gatesOpen || 0), 0);
    const dangerDams = dams.filter((d) => d.safetyStatus === "danger").length;

    const summary = [
      `Total Dams Monitored: ${dams.length}`,
      `Total Gates Open: ${totalGatesOpen}`,
      `Dams in Danger: ${dangerDams}`,
      `Report Period: ${reportType.toUpperCase()}`,
      `Date: ${new Date().toLocaleDateString("en-IN")}`,
    ];

    summary.forEach((line, i) => {
      doc.text(`• ${line}`, 14, 60 + i * 7);
    });

    // Dam Table
    doc.setFontSize(13);
    doc.setFont("helvetica", "bold");
    doc.text("Dam Status Details", 14, 100);

    const headers = ["Dam Name", "State", "Water Level", "Storage %", "Inflow", "Outflow", "Gates", "Status"];
    const colWidths = [40, 22, 22, 22, 20, 20, 16, 18];
    let startX = 14;
    const tableStartY = 108;

    doc.setFillColor(37, 99, 235);
    doc.rect(14, tableStartY, pageWidth - 28, 7, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(8);
    doc.setFont("helvetica", "bold");
    headers.forEach((h, i) => {
      const x = colWidths.slice(0, i).reduce((a, b) => a + b, startX);
      doc.text(h, x + 1, tableStartY + 5);
    });

    doc.setTextColor(0, 0, 0);
    doc.setFont("helvetica", "normal");
    dams.forEach((dam, rowIdx) => {
      const y = tableStartY + 7 + rowIdx * 8;
      if (rowIdx % 2 === 0) {
        doc.setFillColor(248, 250, 252);
        doc.rect(14, y, pageWidth - 28, 8, "F");
      }
      const storagePct = dam.maxCapacity ? ((dam.currentCapacity / dam.maxCapacity) * 100).toFixed(1) : "N/A";
      const row = [
        dam.name.substring(0, 18),
        dam.state || "",
        `${dam.waterLevel?.toFixed(1)} m`,
        `${storagePct}%`,
        `${(dam.inflowRate / 1000).toFixed(0)}k`,
        `${(dam.outflowRate / 1000).toFixed(0)}k`,
        `${dam.gatesOpen}/${dam.totalGates}`,
        (dam.safetyStatus || "").toUpperCase(),
      ];
      row.forEach((cell, i) => {
        const x = colWidths.slice(0, i).reduce((a, b) => a + b, startX);
        if (i === 7) {
          const statusColor = dam.safetyStatus === "danger" ? [220, 38, 38] : dam.safetyStatus === "warning" ? [249, 115, 22] : dam.safetyStatus === "watch" ? [245, 158, 11] : [22, 163, 74];
          doc.setTextColor(statusColor[0], statusColor[1], statusColor[2]);
        } else {
          doc.setTextColor(0, 0, 0);
        }
        doc.text(cell, x + 1, y + 5.5, { maxWidth: colWidths[i] - 2 });
      });
    });

    // Footer
    const finalY = tableStartY + 7 + dams.length * 8 + 15;
    doc.setTextColor(100, 116, 139);
    doc.setFontSize(8);
    doc.text("Generated by DamGuard Smart Monitoring System | Government of India | CONFIDENTIAL", pageWidth / 2, finalY, { align: "center" });

    doc.save(`DamGuard_${reportType}_report_${new Date().toISOString().split("T")[0]}.pdf`);
    setGenerating(null);
  };

  const generateCSV = async () => {
    setGenerating("csv");
    const res = await fetch("/api/dams");
    const json = await res.json();
    const dams: Dam[] = json.dams || [];

    const headers = ["Dam Name", "State", "Water Level (m)", "Max Water Level (m)", "Current Capacity (MCM)", "Max Capacity (MCM)", "Storage %", "Inflow (cusecs)", "Outflow (cusecs)", "Total Gates", "Gates Open", "Safety Status"];
    const rows = dams.map((d) => [
      d.name, d.state, d.waterLevel, d.maxWaterLevel, d.currentCapacity, d.maxCapacity,
      d.maxCapacity ? ((d.currentCapacity / d.maxCapacity) * 100).toFixed(1) : "N/A",
      d.inflowRate, d.outflowRate, d.totalGates, d.gatesOpen, d.safetyStatus,
    ]);

    const csv = [headers, ...rows].map((r) => r.map((v) => `"${v}"`).join(",")).join("\n");
    const blob = new Blob([csv], { type: "text/csv" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `DamGuard_${reportType}_${new Date().toISOString().split("T")[0]}.csv`;
    a.click();
    URL.revokeObjectURL(url);
    setGenerating(null);
  };

  const generateJSON = async () => {
    setGenerating("json");
    const [damsRes, alertsRes, weatherRes] = await Promise.all([
      fetch("/api/dams").then((r) => r.json()),
      fetch("/api/alerts").then((r) => r.json()),
      fetch("/api/weather").then((r) => r.json()),
    ]);

    const report = {
      generatedAt: new Date().toISOString(),
      type: reportType,
      dams: damsRes.dams || [],
      alerts: alertsRes.alerts || [],
      weather: weatherRes.weather || [],
      summary: {
        totalDams: damsRes.dams?.length || 0,
        activeAlerts: alertsRes.alerts?.filter((a: { isResolved: boolean }) => !a.isResolved).length || 0,
        dangerDams: damsRes.dams?.filter((d: Dam) => d.safetyStatus === "danger").length || 0,
      },
    };

    const blob = new Blob([JSON.stringify(report, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `DamGuard_report_${new Date().toISOString().split("T")[0]}.json`;
    a.click();
    URL.revokeObjectURL(url);
    setGenerating(null);
  };

  return (
    <div className="space-y-4">
      {/* Report type selector */}
      <div className="bg-white rounded-2xl p-5 shadow-sm border border-gray-100">
        <h3 className="font-semibold text-gray-800 mb-4">📄 Generate Reports</h3>
        <div className="flex gap-3 mb-4">
          {["daily", "weekly", "monthly"].map((type) => (
            <button
              key={type}
              onClick={() => setReportType(type)}
              className={`px-4 py-2 rounded-xl text-sm font-medium capitalize transition-all ${
                reportType === type ? "bg-blue-600 text-white" : "bg-gray-100 text-gray-600 hover:bg-gray-200"
              }`}
            >
              {type === "daily" ? "📅" : type === "weekly" ? "📆" : "🗓️"} {type} Report
            </button>
          ))}
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          {[
            { label: "PDF Report", desc: "Professional formatted report with charts and tables", icon: "📑", format: "pdf", color: "red", action: generatePDF },
            { label: "CSV Export", desc: "Spreadsheet data for Excel analysis", icon: "📊", format: "csv", color: "green", action: generateCSV },
            { label: "JSON Export", desc: "Full data export for API integration", icon: "⚙️", format: "json", color: "blue", action: generateJSON },
          ].map((item) => (
            <motion.div
              key={item.format}
              whileHover={{ y: -2 }}
              className="bg-gray-50 rounded-2xl p-5 border border-gray-100"
            >
              <div className="text-3xl mb-3">{item.icon}</div>
              <h4 className="font-semibold text-gray-800 mb-1">{item.label}</h4>
              <p className="text-xs text-gray-500 mb-4">{item.desc}</p>
              <button
                onClick={item.action}
                disabled={generating !== null}
                className={`w-full py-2.5 rounded-xl text-sm font-medium transition-all ${
                  generating === item.format
                    ? "bg-gray-200 text-gray-500 cursor-not-allowed"
                    : `bg-${item.color}-600 text-white hover:bg-${item.color}-700`
                } ${item.color === "red" ? "bg-red-600 hover:bg-red-700" : item.color === "green" ? "bg-green-600 hover:bg-green-700" : "bg-blue-600 hover:bg-blue-700"}`}
              >
                {generating === item.format ? (
                  <span className="flex items-center justify-center gap-2">
                    <div className="w-4 h-4 border-2 border-current border-t-transparent rounded-full animate-spin"></div>
                    Generating...
                  </span>
                ) : (
                  `⬇️ Download ${item.label}`
                )}
              </button>
            </motion.div>
          ))}
        </div>
      </div>

      {/* Report Preview */}
      <div className="bg-white rounded-2xl p-5 shadow-sm border border-gray-100">
        <h3 className="font-semibold text-gray-800 mb-4">📋 Report Preview</h3>
        <div className="bg-gray-50 rounded-xl p-6 font-mono text-xs text-gray-600 space-y-2">
          <div className="text-center text-base font-bold text-blue-600 mb-4">DAMGUARD SMART MONITORING SYSTEM</div>
          <div className="text-center mb-4">{reportType.toUpperCase()} STATUS REPORT</div>
          <div className="text-center text-gray-400">{new Date().toLocaleDateString("en-IN", { weekday: "long", year: "numeric", month: "long", day: "numeric" })}</div>
          <hr className="my-3 border-gray-300" />
          <div className="grid grid-cols-2 gap-2">
            <div>• Total Dams: 5</div>
            <div>• Active Alerts: 3</div>
            <div>• Danger Dams: 1</div>
            <div>• Gates Open: 18</div>
            <div>• Total Inflow: 245,400 cusecs</div>
            <div>• Total Outflow: 163,000 cusecs</div>
          </div>
          <hr className="my-3 border-gray-300" />
          <div className="text-center text-gray-400 text-xs">Report contains dam status, water levels, alerts, weather data, and predictions</div>
        </div>
      </div>
    </div>
  );
}
